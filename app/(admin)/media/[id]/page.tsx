import Link from "next/link";
import { notFound } from "next/navigation";
import { displayName, formatDate, requireAdmin } from "@/lib/admin";
import { deleteCaption, updateCaption } from "../actions";
import { CaptionFields, DeleteForm, Flash } from "../shared";

export default async function CaptionPage({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ error?: string; saved?: string }>;
}) {
  const { supabase } = await requireAdmin();
  const { id } = await params;
  const { error, saved } = await searchParams;
  const captionId = Number(id);
  if (!Number.isInteger(captionId)) notFound();

  const { data: caption } = await supabase
    .from("captions")
    .select("id, photo_id, generation_id, caption_text, setup, angle, created_at, photos(image_url, alt_text)")
    .eq("id", captionId)
    .maybeSingle();
  if (!caption) notFound();

  const [{ data: photos }, { data: generation }, { data: votes }] = await Promise.all([
    supabase.from("photos").select("id, alt_text").order("id", { ascending: false }),
    caption.generation_id
      ? supabase
          .from("generations")
          .select("id, user_id, model, kind, system_prompt, user_prompt, context, created_at")
          .eq("id", caption.generation_id)
          .maybeSingle()
      : Promise.resolve({ data: null }),
    supabase.from("caption_votes").select("id, user_id, vote, created_at").eq("caption_id", captionId),
  ]);

  const userIds = [...new Set([generation?.user_id, ...(votes ?? []).map((v) => v.user_id)].filter(Boolean))];
  const { data: profiles } = userIds.length
    ? await supabase.from("profiles").select("id, first_name, last_name").in("id", userIds)
    : { data: [] };
  const profileById = new Map((profiles ?? []).map((p) => [p.id, p]));

  const photo = Array.isArray(caption.photos) ? caption.photos[0] : caption.photos;
  const up = (votes ?? []).filter((v) => v.vote > 0).length;
  const down = (votes ?? []).length - up;

  return (
    <>
      <div className="page-head">
        <div>
          <p className="eyebrow">
            <Link href="/media">Captions</Link> / #{caption.id}
          </p>
          <h1>Edit caption</h1>
        </div>
        <div className="toolbar">
          <span className="pill up">▲ {up}</span>
          <span className="pill down">▼ {down}</span>
        </div>
      </div>

      <Flash error={error} saved={saved} />

      <div className="grid two">
        <form action={updateCaption} className="card">
          <input type="hidden" name="id" value={caption.id} />
          {photo && (
            // eslint-disable-next-line @next/next/no-img-element
            <img src={photo.image_url} alt={photo.alt_text ?? ""} style={{ width: "100%", maxHeight: 280, objectFit: "contain", borderRadius: 8, background: "var(--neutral)" }} />
          )}
          <CaptionFields caption={caption} photos={photos ?? []} />
          <button className="button primary" type="submit">
            Save changes
          </button>
        </form>

        <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
          <section className="card">
            <h2>Provenance</h2>
            <p className="small muted">Created {formatDate(caption.created_at)}</p>
            {generation ? (
              <>
                <p className="small">
                  Generated by <strong>{displayName(profileById.get(generation.user_id))}</strong> with{" "}
                  <code>{generation.model}</code> ({generation.kind})
                </p>
                <details>
                  <summary className="small" style={{ cursor: "pointer" }}>
                    Prompts used
                  </summary>
                  <pre className="small" style={{ whiteSpace: "pre-wrap", marginTop: 8 }}>
                    {`SYSTEM:\n${generation.system_prompt}\n\nUSER:\n${generation.user_prompt}`}
                  </pre>
                </details>
              </>
            ) : (
              <p className="small">Added manually by an admin (no AI generation record).</p>
            )}
          </section>

          <section className="card">
            <h2>Votes ({(votes ?? []).length})</h2>
            {(votes ?? []).length === 0 && <p className="small muted">Nobody has voted yet.</p>}
            {(votes ?? []).map((v) => (
              <div key={v.id} className="small" style={{ display: "flex", justifyContent: "space-between" }}>
                <span>
                  <span className={`pill ${v.vote > 0 ? "up" : "down"}`}>{v.vote > 0 ? "▲" : "▼"}</span>{" "}
                  {displayName(profileById.get(v.user_id), "Anonymous")}
                </span>
                <span className="muted">{formatDate(v.created_at)}</span>
              </div>
            ))}
          </section>

          <DeleteForm
            action={deleteCaption}
            id={caption.id}
            what="caption"
            warning="This removes the caption and all of its votes. The photo stays."
          />
        </div>
      </div>
    </>
  );
}
